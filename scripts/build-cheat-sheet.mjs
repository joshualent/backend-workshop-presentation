#!/usr/bin/env node
/**
 * Writes notes/cheat-sheet.md: every snippet the presenter types or pastes,
 * in order, grouped by part, generated from slides/snippets/ (the real
 * checkpoint files and diffs) so it can't drift from the workshop code.
 *
 *   node scripts/build-cheat-sheet.mjs           # (re)write notes/cheat-sheet.md
 *   node scripts/build-cheat-sheet.mjs --check   # exit 1 if it is out of date
 *
 * The order, "where it goes", and commands are written here; code comes only
 * from the snippet files.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const snippets = join(root, 'slides', 'snippets')
const target = join(root, 'notes', 'cheat-sheet.md')

const read = path => readFileSync(join(snippets, path), 'utf8').replace(/\n$/, '')

/** Per-file sections of a checkpoint's diff, keyed by path. */
function diffsOf(branch) {
  const text = read(`diffs/${branch}.diff`)
  const out = {}
  for (const part of text.split(/^(?=diff --git )/m)) {
    const m = part.match(/^diff --git a\/(\S+) b\//)
    if (m)
      out[m[1]] = part.slice(part.indexOf('@@')).replace(/\n$/, '')
  }
  return out
}

const fence = (lang, body) => `\`\`\`${lang}\n${body}\n\`\`\``
const sh = (...cmds) => fence('bash', cmds.join('\n'))

function fileStep(n, branch, path, where, { diff = true, full = true } = {}) {
  const parts = [`### ${n}. \`${path}\`\n\n${where}`]
  if (diff) {
    const d = diffsOf(branch)[path]
    if (!d)
      throw new Error(`${path} does not change in ${branch}`)
    parts.push(`What changes (\`+\` lines are new, \`-\` lines go away):\n\n${fence('diff', d)}`)
  }
  if (full)
    parts.push(`${diff ? 'The whole file afterwards' : 'The whole file'}, to paste if you fall behind:\n\n${fence('python', read(`${branch}/${path}`))}`)
  return parts.join('\n\n')
}

